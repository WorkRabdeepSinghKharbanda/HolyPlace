// One-off keyword research pass: queries Google Autocomplete (public endpoint,
// no auth) for every figure/chant and a set of blog topic seeds, saves raw
// results to .claude/brain/seo/keywords.json and a readable index to
// .claude/brain/seo/keyword-index.md. Not wired into the build — run by hand
// when expanding content, since autocomplete demand signals drift over time.
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const { religions } = await import(path.join(root, "src/data/religions.ts") + "?t=" + Date.now());
const { festivals } = await import(path.join(root, "src/data/festivals.ts") + "?t=" + Date.now());

async function suggest(seed) {
  const url = `https://suggestqueries.google.com/complete/search?client=firefox&q=${encodeURIComponent(seed)}`;
  try {
    const res = await fetch(url, { headers: { "User-Agent": "Mozilla/5.0" } });
    const data = await res.json();
    return data[1] ?? [];
  } catch (e) {
    console.error(`failed: ${seed}`, e.message);
    return [];
  }
}

function sleep(ms) {
  return new Promise((r) => setTimeout(r, ms));
}

const seeds = new Map(); // seed -> { page, intent }

for (const r of religions) {
  for (const f of r.figures) {
    const page = `/${r.id}/${f.id}`;
    seeds.set(`${f.name} aarti`, { page, intent: "content depth" });
    seeds.set(`${f.name} mantra`, { page, intent: "content depth" });
    seeds.set(`${f.name} chalisa lyrics`, { page, intent: "content depth" });
    seeds.set(`${f.name} mantra meaning`, { page, intent: "content depth" });
    seeds.set(`how to do ${f.name} aarti at home`, { page: "blog", intent: "blog topic" });
    seeds.set(`benefits of chanting ${f.name} mantra`, { page: "blog", intent: "blog topic" });
    for (const c of f.chants) {
      seeds.set(`${c.title} lyrics in english`, { page: `${page}/${c.id}`, intent: "content depth" });
    }
  }
}

for (const fest of festivals) {
  seeds.set(`${fest.name} date 2026`, { page: "blog", intent: "blog topic" });
  seeds.set(`how to celebrate ${fest.name}`, { page: "blog", intent: "blog topic" });
}

// generic devotional intent seeds, not tied to one figure
for (const generic of [
  "mantra for exams",
  "mantra for protection",
  "mantra for new home",
  "best aarti for daily puja",
  "how to start a daily puja routine",
]) {
  seeds.set(generic, { page: "blog", intent: "blog topic" });
}

const results = {};
let i = 0;
for (const [seed, meta] of seeds) {
  i++;
  const suggestions = await suggest(seed);
  results[seed] = { ...meta, suggestions };
  console.log(`[${i}/${seeds.size}] ${seed} -> ${suggestions.length} suggestions`);
  await sleep(150);
}

writeFileSync(path.join(root, ".claude/brain/seo/keywords.json"), JSON.stringify(results, null, 2));

// Build readable index grouped by owning page
const byPage = {};
for (const [seed, data] of Object.entries(results)) {
  const key = data.page;
  byPage[key] ??= [];
  byPage[key].push({ seed, suggestions: data.suggestions, intent: data.intent });
}

let md = "# Keyword index\n\nGenerated by `scripts/keyword-research.mjs` from Google Autocomplete — demand signals, not search volume. Re-run periodically; results drift.\n\n";
for (const [page, entries] of Object.entries(byPage)) {
  md += `## ${page}\n\n`;
  for (const e of entries) {
    md += `- **${e.seed}** (${e.intent})\n`;
    for (const s of e.suggestions.slice(0, 8)) md += `  - ${s}\n`;
  }
  md += "\n";
}
writeFileSync(path.join(root, ".claude/brain/seo/keyword-index.md"), md);

console.log(`\nDone. ${seeds.size} seeds queried.`);
